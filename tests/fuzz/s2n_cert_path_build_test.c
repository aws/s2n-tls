int s2n_fuzz_test(const uint8_t *buf, size_t len)
{
#if S2N_LIBCRYPTO_SUPPORTS_CBS
    /* Treat the fuzz input as a raw wire certificate chain (concatenated DER
     * TLVs). Parse failures are expected on arbitrary input. */
    struct s2n_blob wire_chain = { 0 };
    POSIX_GUARD(s2n_blob_init(&wire_chain, (uint8_t *) (uintptr_t) buf, len));

    struct s2n_cert_chain_spans chain = { 0 };
    if (s2n_result_is_error(s2n_cert_chain_spans_parse(&chain, &wire_chain, 7))) {
        return S2N_SUCCESS;
    }

    /* If parse succeeded, attempt path building against the fixed anchor.
     * The Work_Budget bounds computation, so this cannot run unboundedly. */
    struct s2n_cert_path_policy policy = {
        .max_chain_depth = 10,
        .verification_time = 1780000000, /* ~2026, within the anchor's validity */
        .purpose = 0,
    };

    struct s2n_cert_path path = { 0 };
    /* Path-build failures are expected and fine; we just must not crash. */
    s2n_result_ignore(s2n_cert_path_build(&path, &chain, &s2n_fuzz_snapshot, &policy));
#endif /* S2N_LIBCRYPTO_SUPPORTS_CBS */

    return S2N_SUCCESS;
}

